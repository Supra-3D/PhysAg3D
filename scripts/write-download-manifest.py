"""Publish only verified case identities and immutable ZIP URLs to the website."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--manifest', type=Path, required=True)
parser.add_argument('--revision', required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = json.loads(args.manifest.read_text(encoding='utf-8'))
data = {'sourceRepository': source['sourceRepository'], 'sourceRevision': source['sourceRevision'],
        'downloadRevision': args.revision,
        'baseUrl': f"https://huggingface.co/datasets/{source['sourceRepository']}/resolve/{args.revision}/downloads/{source['sourceRevision'][:12]}/",
        'assets': {row['caseId']: {key: row[key] for key in ('galleryId', 'name', 'file', 'bytes', 'sha256', 'files')} for row in source['assets']}}
assert len(data['assets']) == len(source['assets'])
text = '/* Verified complete case ZIPs; generated by scripts/write-download-manifest.py. */\nwindow.PHYSAG3D_DOWNLOAD_MANIFEST = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
for path in (root / 'download-data.js', root / 'website/download-data.js'):
    path.write_text(text, encoding='utf-8', newline='\n')
print(f"Wrote {len(data['assets'])} verified case download records.")
